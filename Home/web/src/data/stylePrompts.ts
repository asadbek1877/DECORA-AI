/** Given a style name, get a random prompt from the array */
export function getRandomPrompt(styleName: string): string {
  const prompts = stylePrompts[styleName] || stylePrompts.minimalism;
  return prompts[Math.floor(Math.random() * prompts.length)];
}

/** Get the next prompt by index (cycles through the array) */
export function getNextPrompt(styleName: string, currentIndex: number): { prompt: string; nextIndex: number } {
  const prompts = stylePrompts[styleName] || stylePrompts.minimalism;
  const next = (currentIndex + 1) % prompts.length;
  return { prompt: prompts[next], nextIndex: next };
}
